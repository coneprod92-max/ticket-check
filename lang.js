const languageNames = {
  fr: "🇫🇷 Français",
  en: "🇬🇧 English",
  de: "🇩🇪 Deutsch",
  es: "🇪🇸 Español"
};

const storageKey = "ticketcheck_language";

function getLanguage() {
  const saved = localStorage.getItem(storageKey);
  return translations[saved] ? saved : "fr";
}

let currentLanguage = getLanguage();

function t(key) {
  return translations[currentLanguage]?.[key]
    ?? translations.fr[key]
    ?? key;
}

function applyTranslations() {
  document.documentElement.lang = currentLanguage;

  document.querySelectorAll("[data-i18n]").forEach(element => {
    const key = element.dataset.i18n;
    if (t(key)) element.textContent = t(key);
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach(element => {
    const key = element.dataset.i18nPlaceholder;
    if (t(key)) element.placeholder = t(key);
  });

  document.querySelectorAll("[data-i18n-value]").forEach(element => {
    const key = element.dataset.i18nValue;
    if (t(key)) element.value = t(key);
  });

  document.querySelectorAll("[data-i18n-title]").forEach(element => {
    const key = element.dataset.i18nTitle;
    if (t(key)) element.title = t(key);
  });

  const selector = document.getElementById("ticketcheck-language");
  if (selector) selector.value = currentLanguage;

  document.dispatchEvent(new CustomEvent("ticketcheck:languageChanged", {
    detail: { language: currentLanguage }
  }));
}

function setLanguage(language) {
  if (!translations[language]) return;

  currentLanguage = language;
  localStorage.setItem(storageKey, language);
  applyTranslations();
}

function createLanguageSelector() {
  const header = document.querySelector(".navbar");
  if (!header || document.getElementById("ticketcheck-language")) return;

  const selector = document.createElement("select");
  selector.id = "ticketcheck-language";
  selector.setAttribute("aria-label", "Choose language");

  Object.entries(languageNames).forEach(([code, name]) => {
    const option = document.createElement("option");
    option.value = code;
    option.textContent = name;
    selector.appendChild(option);
  });

  selector.value = currentLanguage;

  selector.style.cssText = `
    background:#102640;
    color:#ffffff;
    border:1px solid rgba(255,255,255,.2);
    border-radius:8px;
    padding:10px 12px;
    font-size:13px;
    font-weight:600;
    cursor:pointer;
    max-width:145px;
    margin-left:auto;
  `;

  selector.addEventListener("change", event => {
    setLanguage(event.target.value);
  });

  const freeButton = header.querySelector(".free-btn");

  if (freeButton) {
    header.insertBefore(selector, freeButton);
  } else {
    header.appendChild(selector);
  }
}

window.TicketCheckI18n = {
  t,
  setLanguage,
  getLanguage: () => currentLanguage,
  applyTranslations,
  translations
};

createLanguageSelector();
applyTranslations();

document.addEventListener("DOMContentLoaded", () => {
  createLanguageSelector();
  applyTranslations();
});
